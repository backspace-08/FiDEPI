export const QUESTIONS_TOTAL = QUESTIONS.length

export const QUESTION_BY_N = new Map(QUESTIONS.map((q) => [q.n, q]))

export function pickQuestions(limit) {
  if (!limit || limit >= QUESTIONS.length) return [...QUESTIONS]
  const groups = BLOCK_ORDER.map((block) => QUESTIONS.filter((q) => q.block === block))
  const picked = []
  for (let round = 0; picked.length < limit; round += 1) {
    for (const group of groups) {
      if (group[round]) picked.push(group[round])
      if (picked.length >= limit) break
    }
  }
  return picked.slice(0, limit)
}
